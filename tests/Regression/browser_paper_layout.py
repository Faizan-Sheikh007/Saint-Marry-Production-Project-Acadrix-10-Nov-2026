"""Synthetic A4 question-paper browser/PDF regressions, not a live Laravel test."""
from __future__ import annotations
import json, os, re
from pathlib import Path
import fitz
from playwright.sync_api import sync_playwright

ROOT = Path(os.environ.get('ACADRIX_QA_OUTPUT', '/tmp/acadrix-report-status'))
BROWSER = os.environ.get('CHROMIUM_BIN', '/usr/bin/chromium')
NAMES = ['layout-single','layout-all-types','layout-diagram','layout-escaped','layout-long','layout-oversized','layout-empty']
RESULTS=[]
CHECKS=[]

def check(condition, label):
    if not condition: raise AssertionError(label)
    CHECKS.append(label)

def normalized(text):
    return ' '.join(text.split())

with sync_playwright() as pw:
    browser = pw.chromium.launch(executable_path=BROWSER, headless=True, args=['--no-sandbox'])
    page = browser.new_page(viewport={'width':1200,'height':1000})
    errors=[]
    page.on('pageerror', lambda exc:errors.append(str(exc)))
    for name in NAMES:
        page.set_content((ROOT / f'{name}.html').read_text(), wait_until='load')
        page.wait_for_function('document.body.classList.contains("is-paginated")')
        # Running twice also covers beforeprint and re-pagination idempotence.
        page.wait_for_timeout(250)
        count=page.locator('#paper-pages > .sheet').count()
        check(count >= 1, f'{name}: paginated sheet exists')
        check(page.locator('#paper-source').is_hidden(), f'{name}: unpaginated source hidden')
        check(page.locator('.page-navigation').count() == (count if count>1 else 0), f'{name}: footer only for multi-page')
        check(page.locator('.turn-over').count()==max(0,count-1), f'{name}: Turn Over on every nonfinal page')
        check(page.locator('.details-grid .metadata-line').count()==2, f'{name}: two metadata rows (hidden source only)')
        check(page.locator('#paper-pages .metadata-line').count()==2, f'{name}: visible metadata only first page')
        row_info=page.locator('#paper-pages .metadata-line').evaluate_all('rows => rows.map(row => Array.from(row.children).map(cell => ({y:cell.getBoundingClientRect().top, r:cell.getBoundingClientRect().right})))')
        check(all(max(c['y'] for c in row)-min(c['y'] for c in row)<1 for row in row_info), f'{name}: metadata values align horizontally')
        body_right=page.locator('#paper-pages .page-content').first.evaluate('(el)=>el.getBoundingClientRect().right')
        check(all(max(c['r'] for c in row) <= body_right+1 for row in row_info), f'{name}: metadata stays inside A4 printable region')
        check(page.locator('#paper-pages .sheet').first.evaluate('(el)=>getComputedStyle(el).borderTopWidth')=='0px', f'{name}: no outer border')
        for i in range(count):
            sheet=page.locator('#paper-pages > .sheet').nth(i)
            check(sheet.locator('.page-content').evaluate('(el)=>el.scrollHeight<=el.clientHeight+2'), f'{name}/p{i+1}: page body does not overflow')
        for mode in ['headers-off','headers-on']:
            filename=ROOT / f'{name}-{mode}.pdf'
            page.pdf(path=str(filename),prefer_css_page_size=True,print_background=True,display_header_footer=(mode=='headers-on'))
            with fitz.open(filename) as document:
                check(len(document)==count, f'{name}/{mode}: exactly one A4 PDF page per screen sheet')
                all_text='\n'.join(p.get_text() for p in document)
                for forbidden in ['Bugs and errors are applicable', 'Digitally generated by Acadrix', 'Sample Teacher', 'Exam Date', 'about:blank', 'Print on A4']:
                    check(forbidden not in all_text, f'{name}/{mode}: removed text {forbidden!r}')
                if name == 'layout-single':
                    check(count==1, f'{name}/{mode}: representative paper fits on one page')
                if name in ('layout-long','layout-oversized'):
                    check(count>1, f'{name}/{mode}: long paper spans multiple pages')
                if name == 'layout-long':
                    for i in range(1,81):
                        check(all_text.count(f'QUESTION_TOKEN_{i:03d}')==1, f'{name}/{mode}: unique question {i}')
                if name == 'layout-oversized':
                    check(normalized(all_text).count('intentionally oversized synthetic question')==75, f'{name}/{mode}: all oversized text retained')
                    check('OVERSIZED_QUESTION_START' in all_text and 'OVERSIZED_QUESTION_END' in all_text, f'{name}/{mode}: oversized question start/end')
                if name == 'layout-escaped':
                    check('UNTRUSTED_HTML' in all_text and 'alert(1)' in all_text, f'{name}/{mode}: escaped text preserved')
                if name in ('layout-all-types','layout-diagram'):
                    for i in range(1,6):
                        check(all_text.count(f'SECTION_TOKEN_{i}')==1, f'{name}/{mode}: section {i} present once')
                for i, pdf_page in enumerate(document,1):
                    text=normalized(pdf_page.get_text())
                    check(abs(pdf_page.rect.width-595.28)<2 and abs(pdf_page.rect.height-841.89)<2,f'{name}/{mode}/p{i}: A4 paper')
                    if count==1:
                        check('Page 1 of 1' not in text and 'Turn Over' not in text, f'{name}/{mode}/p{i}: no unnecessary pagination')
                    else:
                        check(f'Page {i} of {count}' in text, f'{name}/{mode}/p{i}: correct page count')
                        check(('TURN OVER' in text.upper())==(i<count), f'{name}/{mode}/p{i}: Turn Over only if next page')
                        footer_rect=[b for b in pdf_page.get_text('blocks') if f'Page {i} of {count}' in normalized(b[4])]
                        check(len(footer_rect)==1, f'{name}/{mode}/p{i}: exactly one page navigation')
                        body=[b for b in pdf_page.get_text('blocks') if b[4].strip() and f'Page {i} of {count}' not in normalized(b[4]) and 'Turn Over' not in normalized(b[4])]
                        check(all(b[3] < footer_rect[0][1] - 5 for b in body),f'{name}/{mode}/p{i}: no body/footer overlap')
                    check('Sample Teacher' not in text, f'{name}/{mode}/p{i}: no teacher')
            RESULTS.append({'fixture':name,'mode':mode,'pages':count})
        if name in ['layout-single','layout-long','layout-oversized']:
            page.screenshot(path=str(ROOT / f'{name}-browser-preview.png'),full_page=True)
    check(not errors,f'no browser JS errors: {errors}')
    version=browser.version
    browser.close()
report={'checks_passed':len(CHECKS),'chromium':version,'results':RESULTS,'notes':'Synthetic HTML fixtures; not a live authenticated Laravel or physical printer test.'}
(ROOT/'paper-layout-browser-validation.json').write_text(json.dumps(report,indent=2))
print(f'PASS: {len(CHECKS)} question-paper layout checks across {len(RESULTS)} browser PDF outputs, Chromium {version}.')
